"""F3 exploratory breakdown. NOT pre-registered; report only; never used for selection.

Reads forecast/out/f3/predictions.csv (selection folds only) and writes
forecast/out/f3/exploratory.md:
  - which model has the lowest WAPE in each fold
  - bias and WAPE by weekday of the forecast date
  - pooled WAPE with one fold left out at a time (how much one week moves the ranking)

    python forecast/explore_f3.py           write
    python forecast/explore_f3.py --check   fail if the file on disk differs
"""
from __future__ import annotations

import collections
import csv
import datetime as dt
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
F3 = HERE / "out" / "f3"
MODELS = ("seasonal_naive", "calendar_regression", "chronos2")
WEEKDAYS = ("Tue", "Wed", "Thu", "Fri", "Sat", "Sun", "Mon")   # horizon 1..7 from a Monday origin


def _wape(rows):
    return sum(abs(int(r["p50"]) - int(r["actual"])) for r in rows) / sum(int(r["actual"]) for r in rows)


def _bias(rows):
    return sum(int(r["p50"]) - int(r["actual"]) for r in rows) / sum(int(r["actual"]) for r in rows)


def build() -> str:
    with open(F3 / "predictions.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    by = collections.defaultdict(list)
    for r in rows:
        by[(r["model"], r["as_of"])].append(r)
    folds = sorted({r["as_of"] for r in rows})
    pct = lambda x: f"{100 * x:.1f}%"  # noqa: E731
    out = ["# F3 exploratory breakdown (not pre-registered; report only; not used for selection)", "",
           "Generated by forecast/explore_f3.py from forecast/out/f3/predictions.csv (selection folds only).", "",
           "## Lowest WAPE per fold", "", "| as_of | best | " + " | ".join(MODELS) + " |", "|---|---|" + "---|" * len(MODELS)]
    wins = collections.Counter()
    for o in folds:
        w = {m: _wape(by[(m, o)]) for m in MODELS}
        best = min(w, key=w.get)
        wins[best] += 1
        out.append(f"| {o} | {best} | " + " | ".join(pct(w[m]) for m in MODELS) + " |")
    out += ["", "Folds won: " + ", ".join(f"{m} {wins[m]}" for m in MODELS), ""]

    out += ["## By weekday of the forecast date (bias / WAPE)", "", "| weekday | " + " | ".join(MODELS) + " |",
            "|---|" + "---|" * len(MODELS)]
    for wd in WEEKDAYS:
        cells = []
        for m in MODELS:
            rr = [r for r in rows if r["model"] == m and dt.date.fromisoformat(r["date"]).strftime("%a") == wd]
            cells.append(f"{pct(_bias(rr))} / {pct(_wape(rr))}")
        out.append(f"| {wd} | " + " | ".join(cells) + " |")

    out += ["", "## Pooled WAPE leaving one fold out", "", "| fold left out | " + " | ".join(MODELS) + " | lowest |",
            "|---|" + "---|" * len(MODELS) + "---|"]
    for o in folds:
        w = {m: _wape([r for r in rows if r["model"] == m and r["as_of"] != o]) for m in MODELS}
        out.append(f"| {o} | " + " | ".join(pct(w[m]) for m in MODELS) + f" | {min(w, key=w.get)} |")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    text = build()
    path = F3 / "exploratory.md"
    if argv and "--check" in argv:
        ok = path.exists() and path.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print("OK: exploratory.md reproduces" if ok else "FAILED: exploratory.md differs", file=sys.stdout if ok else sys.stderr)
        return 0 if ok else 1
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
